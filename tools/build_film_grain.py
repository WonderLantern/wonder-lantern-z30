"""Rebuild the film grain payload from modules/film_grain (needs arm-none-eabi-gcc).

Writes src/z30_extensions/features/photo/film_grain_payload.py, so normal
firmware builds (CLI, GUI, the exe) never need a C compiler. --check only
verifies that the committed payload matches a fresh build.

The committed payload is built with arm-none-eabi-gcc GCC_VERSION (Arm GNU
Toolchain 13.2.Rel1), the same compiler as the gyro e-VR payload; other
versions emit different code, so --check only matches with that version.
"""
import argparse, hashlib, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src' / 'z30_extensions' / 'features' / 'photo' / 'film_grain_payload.py'
GCC_VERSION = '13.2.1'


def compiler_version():
    try:
        return subprocess.run(['arm-none-eabi-gcc', '-dumpversion'], capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def build():
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / 'film_grain.bin'
        subprocess.run(['sh', str(ROOT / 'modules' / 'film_grain' / 'build.sh'), str(out)], check=True)
        code = out.read_bytes()
    return code + bytes(-len(code) % 4)


def render(code):
    lines = [code[i:i + 48].hex() for i in range(0, len(code), 48)]
    body = '\n'.join(f"    '{line}'" for line in lines)
    return ('"""Generated by tools/build_film_grain.py from modules/film_grain/film_grain.c '
            f'with arm-none-eabi-gcc {GCC_VERSION}. Do not edit."""\n'
            f"SHA256 = '{hashlib.sha256(code).hexdigest()}'\n"
            f'SIZE = {len(code)}\n'
            f'CODE = bytes.fromhex(\n{body}\n)\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    found = compiler_version()
    text = render(build())
    if args.check:
        same = OUT.is_file() and OUT.read_text() == text
        print('payload matches source' if same else 'payload differs from a fresh build')
        if not same and found != GCC_VERSION:
            print(f'arm-none-eabi-gcc {found or "not found"}: the committed payload is built with {GCC_VERSION}')
        sys.exit(0 if same else 1)
    if found != GCC_VERSION:
        print(f'warning: arm-none-eabi-gcc {found or "not found"}, the committed payload uses {GCC_VERSION}')
    OUT.write_text(text)
    code = build()
    print(f'Wrote {OUT.relative_to(ROOT)}: {len(code)} bytes, sha256 {hashlib.sha256(code).hexdigest()}')


if __name__ == '__main__':
    main()
