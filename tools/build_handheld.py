"""Rebuild the built-in handheld (Game Boy) payload from modules/handheld (needs arm-none-eabi-gcc).

Writes src/z30_extensions/features/experimental/handheld_payload.py, so normal firmware builds
(CLI, GUI, the exe) never need a C compiler. --check only verifies that the
committed payload matches a fresh build.

The committed payload is built with arm-none-eabi-gcc GCC_VERSION (Arm GNU
Toolchain 13.2.Rel1; on Debian / Ubuntu the gcc-arm-none-eabi package
15:13.2.rel1-2). Other versions emit different code so --check only matches with that version; on a mismatch it names the compiler it found.
"""
import argparse, hashlib, os, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src' / 'z30_extensions' / 'features' / 'experimental' / 'handheld_payload.py'
FLAGS = []
GCC_VERSION = '13.2.1'


def compiler_version():
    try:
        return subprocess.run(['arm-none-eabi-gcc', '-dumpversion'], capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def build():
    with tempfile.TemporaryDirectory() as tmp:
        out, elf = Path(tmp) / 'handheld.bin', Path(tmp) / 'handheld.elf'
        subprocess.run(['sh', str(ROOT / 'modules' / 'handheld' / 'build.sh'), str(out), *FLAGS], check=True,
                       env=dict(os.environ, KEEP_ELF=elf.as_posix()))
        code = out.read_bytes()
        symbols = subprocess.run(['arm-none-eabi-nm', str(elf)], capture_output=True, text=True,
                                 check=True).stdout
    code += bytes(-len(code) % 4)
    # The payload's state block H, for the QEMU probe (tools/probe_handheld_qemu.py).
    state = next(int(line.split()[0], 16) for line in symbols.splitlines() if line.split()[-1] == 'H')
    return code, state


def render(code, state):
    lines = [code[i:i + 48].hex() for i in range(0, len(code), 48)]
    body = '\n'.join(f"    '{line}'" for line in lines)
    return (f'"""Generated by tools/build_handheld.py from modules/handheld/handheld.c '
            f'with arm-none-eabi-gcc {GCC_VERSION}. Do not edit."""\n'
            f"SHA256 = '{hashlib.sha256(code).hexdigest()}'\n"
            f'SIZE = {len(code)}\n'
            f'STATE_OFFSET = {state:#x}   # struct hh H (modules/handheld/handheld.c)\n'
            f'CODE = bytes.fromhex(\n{body}\n)\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    found = compiler_version()
    code, state = build()
    text = render(code, state)
    if args.check:
        same = OUT.is_file() and OUT.read_text() == text
        print('payload matches source' if same else 'payload differs from a fresh build')
        if not same and found != GCC_VERSION:
            print(f'arm-none-eabi-gcc {found or "not found"}: the committed payload is built with {GCC_VERSION} '
                  '(docs/handheld.md)')
        sys.exit(0 if same else 1)
    if found != GCC_VERSION:
        print(f'warning: arm-none-eabi-gcc {found or "not found"}, the committed payload uses {GCC_VERSION}')
    OUT.write_text(text)
    print(f'Wrote {OUT.relative_to(ROOT)}: {len(code)} bytes, sha256 {hashlib.sha256(code).hexdigest()}')


if __name__ == '__main__':
    main()
