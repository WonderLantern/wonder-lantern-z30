"""Write modules/handheld/demo_rom.h: the built-in Game Boy demo of the handheld page.

A few hundred bytes of hand-assembled SM83 code, written for this project (no
third-party ROM data, no logo): "Z30" in block letters on a grid, the D-pad
scrolls the picture, A and B change the palette while held, START recentres.
The handheld runs it when the card has no Z30/GAME.GB, so the page can be
tried (and tested in QEMU, which has no SD card) without any game.
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'modules' / 'handheld' / 'demo_rom.h'
FONT = {'Z': ('111', '001', '010', '100', '111'),
        '3': ('111', '001', '011', '001', '111'),
        '0': ('111', '101', '101', '101', '111')}


def rom():
    code = bytearray()
    labels, fixups = {}, []

    def emit(*b): code.extend(b)
    def here(name): labels[name] = 0x150 + len(code)
    def jr(op, name):            # relative jump to a label (resolved later)
        emit(op, 0); fixups.append((len(code) - 1, name))
    def word(v): emit(v & 255, v >> 8)

    emit(0xF3); emit(0x31); word(0xFFFE)                       # di; ld sp,$fffe
    here('vbl'); emit(0xF0, 0x44, 0xFE, 144); jr(0x38, 'vbl')  # wait LY >= 144
    emit(0xAF, 0xE0, 0x40)                                     # LCD off
    emit(0x21); word(0x8000); emit(0x11); fixups_tiles = len(code); word(0); emit(0x01); word(48)
    here('copy'); emit(0x1A, 0x22, 0x13, 0x0B, 0x78, 0xB1); jr(0x20, 'copy')
    emit(0x21); word(0x9800); emit(0x01); word(1024)
    here('fill'); emit(0x3E, 2, 0x22, 0x0B, 0x78, 0xB1); jr(0x20, 'fill')
    emit(0x11); fixups_dots = len(code); word(0)
    here('dot'); emit(0x1A, 0x13, 0x6F, 0x1A, 0x13, 0x67, 0xB7); jr(0x28, 'shown')
    emit(0x3E, 1, 0x77); jr(0x18, 'dot')
    here('shown'); emit(0x3E, 0xE4, 0xE0, 0x47, 0x3E, 0x91, 0xE0, 0x40)   # palette, LCD on
    here('main'); emit(0xF0, 0x44, 0xFE, 144); jr(0x20, 'main')            # wait LY == 144
    for select, reg in ((0x20, 0x47), (0x10, 0x4F)):                       # D-pad -> B, buttons -> C
        emit(0x3E, select, 0xE0, 0x00, 0xF0, 0x00, 0xF0, 0x00, 0x2F, 0xE6, 0x0F, reg)
    emit(0x3E, 0x30, 0xE0, 0x00)
    emit(0xF0, 0x43, 0xCB, 0x40, 0x28, 1, 0x3D, 0xCB, 0x48, 0x28, 1, 0x3C, 0xE0, 0x43)  # right/left: SCX
    emit(0xF0, 0x42, 0xCB, 0x50, 0x28, 1, 0x3C, 0xCB, 0x58, 0x28, 1, 0x3D, 0xE0, 0x42)  # up/down: SCY
    emit(0x3E, 0xE4, 0xCB, 0x41, 0x28, 2, 0x3E, 0x1B, 0xCB, 0x49, 0x28, 2, 0x3E, 0x93, 0xE0, 0x47)
    emit(0xCB, 0x59, 0x28, 5, 0xAF, 0xE0, 0x42, 0xE0, 0x43)                # START: recentre
    here('leave'); emit(0xF0, 0x44, 0xFE, 144); jr(0x28, 'leave')
    jr(0x18, 'main')
    # Tiles: 0 blank, 1 solid dark, 2 light grid.
    tiles = 0x150 + len(code)
    emit(*bytes(16))
    emit(*(b'\xff' * 16))
    emit(0x00, 0xFF, *(b'\x7f\x80' * 7))
    dots = 0x150 + len(code)
    for i, ch in enumerate('Z30'):
        for y, row in enumerate(FONT[ch]):
            for x, bit in enumerate(row):
                if bit == '1':
                    word(0x9800 + (6 + y) * 32 + 4 + i * 4 + x)
    word(0)
    for at, name in fixups:
        delta = labels[name] - (0x150 + at + 1)
        assert -128 <= delta < 128, name
        code[at] = delta & 255
    code[fixups_tiles:fixups_tiles + 2] = tiles.to_bytes(2, 'little')
    code[fixups_dots:fixups_dots + 2] = dots.to_bytes(2, 'little')

    image = bytearray(0x150) + code
    image[0x100:0x104] = bytes((0x00, 0xC3, 0x50, 0x01))              # nop; jp $0150
    image[0x134:0x13C] = b'Z30 DEMO'
    image[0x147:0x14A] = bytes((0, 0, 0))                              # ROM only, 32 KiB, no RAM
    check = 0
    for b in image[0x134:0x14D]:
        check = (check - b - 1) & 255
    image[0x14D] = check
    return bytes(image)


def main():
    data = rom()
    lines = [', '.join(f'0x{b:02x}' for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    OUT.write_text('/* Generated by tools/make_handheld_demo.py. Do not edit. */\n'
                   f'#define DEMO_ROM_BYTES {len(data)}u\n'
                   'static const unsigned char DEMO_ROM[DEMO_ROM_BYTES] = {\n    '
                   + ',\n    '.join(lines) + '\n};\n')
    print(f'Wrote {OUT}: {len(data)} bytes')


if __name__ == '__main__':
    main()
