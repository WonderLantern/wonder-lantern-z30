"""Rebuild the built-in gyro e-VR payload from modules/gyro_evr (needs arm-none-eabi-gcc).

Writes src/z30_extensions/features/gyro_evr_payload.py, so normal firmware builds
(CLI, GUI, the exe) never need a C compiler. --check only verifies that the
committed payload matches a fresh build.
"""
import argparse, hashlib, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'src' / 'z30_extensions' / 'features' / 'gyro_evr_payload.py'
FLAGS = ['-DEVR_PRODUCT']


def build():
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / 'gyro_evr.bin'
        subprocess.run(['sh', str(ROOT / 'modules' / 'gyro_evr' / 'build.sh'), str(out), *FLAGS], check=True)
        code = out.read_bytes()
    code += bytes(-len(code) % 4)
    return code


def render(code):
    lines = [code[i:i + 48].hex() for i in range(0, len(code), 48)]
    body = '\n'.join(f"    '{line}'" for line in lines)
    return (f'"""Generated by tools/build_gyro_evr.py from modules/gyro_evr/gyro_evr.c '
            f'({" ".join(FLAGS)}). Do not edit."""\n'
            f"SHA256 = '{hashlib.sha256(code).hexdigest()}'\n"
            f'SIZE = {len(code)}\n'
            f'CODE = bytes.fromhex(\n{body}\n)\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    code = build()
    text = render(code)
    if args.check:
        same = OUT.is_file() and OUT.read_text() == text
        print('payload matches source' if same else 'payload differs from a fresh build')
        sys.exit(0 if same else 1)
    OUT.write_text(text)
    print(f'Wrote {OUT.relative_to(ROOT)}: {len(code)} bytes, sha256 {hashlib.sha256(code).hexdigest()}')


if __name__ == '__main__':
    main()
